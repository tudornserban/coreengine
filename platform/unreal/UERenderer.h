#include <cstdint>
#include <string>
#include <unordered_map>
#include <vector>

namespace CoreEngine {
namespace Unreal {

/// Toggleable 3D visual overlays for placeholder 3D testing in UE5.
struct UE3DOverlayFlags {
    bool showVelocityArrows = true;
    bool showPropulsionAndImpulse = true;
    bool showPerceptionCircles = false;
    bool showInfluenceField = true;
    bool showAttackRanges = false;
    bool showObstaclesAndBounds = true;
    bool showTerritoryGrid = false;
    bool showStateBadges = true;
    bool showProjectilesAndExplosions = true;
};

/// Basic 3D primitive shapes emitted by UERenderer for zero-asset UE5 placeholder rendering.
enum class UE3DPrimitiveKind : uint8_t {
    Capsule = 0,
    Cylinder = 1,
    Cone = 2,
    Sphere = 3,
    WireSphere = 4,
    Box = 5,
    Arrow3D = 6,
    Ring3D = 7,
    Quad3D = 8,
    Line3D = 9,
    TextBadge3D = 10
};

struct UE3DPrimitive {
    UE3DPrimitiveKind kind = UE3DPrimitiveKind::Capsule;
    UETransform transform;
    UEVec3 endPoint{0.0f, 0.0f, 0.0f};
    float radius = 10.0f;
    float halfHeight = 20.0f;
    float thickness = 2.0f;
    UEColor color;
    std::string text;
    uint64_t ownerEntityId = 0;
};

/// Per-unit 3D render proxy computed each frame by UERenderer.
struct UE3DUnitRenderProxy {
    uint64_t entityId = 0;
    int team = 0;
    UETransform bodyTransform;
    UETransform headingConeTransform;
    float collisionRadiusUE = 100.0f;
    float visualRadiusUE = 100.0f;
    float capsuleHalfHeightUE = 120.0f;

    float currentHP = 100.0f;
    float maxHP = 100.0f;
    float hpFraction = 1.0f;
    bool isSelected = false;
    bool isDead = false;
    bool inDebugMode = false;

    std::string activeBehaviorState;
    bool transitionedThisTick = false;
    std::string transitionFrom;
    std::string transitionTo;

    UEVec3 velocityArrowStartUE;
    UEVec3 velocityArrowEndUE;
    UEVec3 propulsionArrowEndUE;
    UEVec3 impulseArrowEndUE;
    bool hasTarget = false;
    UEVec3 targetPositionUE;

    float perceptionRadiusUE = 0.0f;
    float influenceRadiusUE = 0.0f;
    float attackRangeUE = 0.0f;

    UEColor bodyColor;
    UEColor ringColor;
};

struct UE3DProjectileProxy {
    uint64_t projectileId = 0;
    uint64_t ownerId = 0;
    int team = 0;
    UEVec3 positionUE;
    UEVec3 velocityUE;
    float radiusUE = 20.0f;
    UEColor color;
};

struct UE3DExplosionEchoProxy {
    UEVec3 positionUE;
    float radiusUE = 100.0f;
    float ageSeconds = 0.0f;
    float maxLifetimeSeconds = 0.5f;
    UEColor color;
};

struct UE3DObstacleProxy {
    UEVec3 positionUE;
    float radiusUE = 100.0f;
    float heightUE = 200.0f;
    bool isAttractor = false;
    float strength = 0.0f;
    UEColor color;
};

/// Complete 3D placeholder scene snapshot generated by UERenderer::Render().
struct UE3DRenderFrame {
    uint32_t simulationTick = 0;
    UEVec3 arenaMinUE{0.0f, 0.0f, 0.0f};
    UEVec3 arenaMaxUE{0.0f, 0.0f, 0.0f};
    bool hasSelectionBox = false;
    UEVec3 selectionBoxMinUE{0.0f, 0.0f, 0.0f};
    UEVec3 selectionBoxMaxUE{0.0f, 0.0f, 0.0f};

    std::vector<UE3DUnitRenderProxy> units;
    std::vector<UE3DProjectileProxy> projectiles;
    std::vector<UE3DExplosionEchoProxy> explosions;
    std::vector<UE3DObstacleProxy> obstaclesAndAttractors;
    std::vector<UE3DPrimitive> primitives;
};

} // namespace Unreal
} // namespace CoreEngine

/// Unreal Engine 5 renderer adapter implementing IGameLogicRenderer.
/// Generates a complete 3D placeholder scene (capsules, orientation nose cones,
/// velocity/propulsion/impulse 3D vectors, state machine badges, radii, obstacles,
/// projectiles, explosion echoes, and territory cells) ready for UE5 Actors,
/// UInstancedStaticMeshComponent, or DrawDebugHelpers with zero 3D asset overhead.
class UERenderer : public IGameLogicRenderer {
private:
    const RTSGameState* state_ = nullptr;
    const TerritoryCalculator* territory_ = nullptr;
    CoreEngine::Unreal::UECoordinateBridge bridge_;
    CoreEngine::Unreal::UE3DOverlayFlags overlays_;
    CoreEngine::Unreal::UE3DRenderFrame lastFrame_;
    std::unordered_map<uint64_t, float> lastUnitHeadingYaw_;
    std::vector<CoreEngine::Unreal::UE3DExplosionEchoProxy> explosionEchoes_;
    float explosionEchoLifetime_ = 0.5f;

public:
    explicit UERenderer(CoreEngine::Unreal::UECoordinateBridge bridge = CoreEngine::Unreal::UECoordinateBridge{})
        : bridge_(std::move(bridge)) {}

    void SetGameState(const RTSGameState* state) { state_ = state; }
    const RTSGameState* GetCurrentGameState() const override { return state_; }
    const ISimulationSnapshot* GetSimulationSnapshot() const override { return state_; }

    void SetTerritoryCalculator(const TerritoryCalculator* territory) { territory_ = territory; }
    const TerritoryCalculator* GetTerritoryCalculator() const { return territory_; }

    CoreEngine::Unreal::UECoordinateBridge& GetCoordinateBridge() { return bridge_; }
    const CoreEngine::Unreal::UECoordinateBridge& GetCoordinateBridge() const { return bridge_; }

    CoreEngine::Unreal::UE3DOverlayFlags& GetOverlayFlags() { return overlays_; }
    const CoreEngine::Unreal::UE3DOverlayFlags& GetOverlayFlags() const { return overlays_; }
    void SetOverlayFlags(const CoreEngine::Unreal::UE3DOverlayFlags& flags) { overlays_ = flags; }

    /// Capture pending explosions before RTSGameState::Update clears them at the end of a tick.
    void NotePendingExplosions();

    /// Advance explosion echo timers and build the latest 3D render frame from RTSGameState.
    void Render(float renderDeltaTime);

    /// Parameterless Render() for compatibility with standard render loop callers.
    void Render() { Render(1.0f / 60.0f); }

    const CoreEngine::Unreal::UE3DRenderFrame& GetLastRenderFrame() const { return lastFrame_; }
    void ClearHistory() {
        lastUnitHeadingYaw_.clear();
        explosionEchoes_.clear();
        lastFrame_ = CoreEngine::Unreal::UE3DRenderFrame{};
    }
};
